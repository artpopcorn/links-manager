#!/bin/bash

echo "╔═══════════════════════════════════════════════════════════════════╗"
echo "║     🚀 Запуск локальной разработки с БД на VDS                   ║"
echo "╚═══════════════════════════════════════════════════════════════════╝"
echo ""

# Останавливаем старые SSH туннели
killall ssh 2>/dev/null
sleep 1

# Создаем SSH туннель
echo "🔌 Создаем SSH туннель к БД на VDS..."
ssh -f -N -L 5434:localhost:5432 root@109.205.58.19

if [ $? -eq 0 ]; then
    echo "✅ SSH туннель создан на порту 5434"
else
    echo "❌ Ошибка создания SSH туннеля"
    exit 1
fi

sleep 2

echo ""
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo "  Подключение к БД: localhost:5434 → VDS PostgreSQL"
echo "━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━"
echo ""

# Запускаем dev сервер
echo "🚀 Запускаем Next.js dev сервер..."
echo ""
npm run dev
